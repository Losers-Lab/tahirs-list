import { Plugin } from "@opencode/plugin"
import { spawn } from "node:child_process"
import { appendFileSync } from "node:fs"

const UVX = "C:/Users/arham/.local/bin/uvx.exe"
const KB_DIR = "C:\\Users\\arham\\programs\\tahirs-list-kb"
const TTL_MS = 10 * 60 * 1000
const LOG = "C:\\Users\\arham\\AppData\\Local\\Temp\\opencode\\bm-brief-debug.log"

function dlog(m: string) {
  try {
    appendFileSync(LOG, `${new Date().toISOString()} [bm-brief] ${m}\n`)
  } catch {}
}

export default Plugin.define({
  id: "basic-memory-brief",
  async setup(ctx) {
    const dir: string = ctx.location.project?.canonical ?? ctx.location.directory ?? ""
    if (!dir.toLowerCase().includes("tahirs-list")) return
    dlog(`setup dir=${dir}`)

    // Spawn Basic Memory CLI commands. The hook protocol (`hook session-start`)
    // reads a payload from stdin, so stdin is closed immediately; otherwise the
    // process would wait forever when spawned without a TTY.
    const runBM = (args: string[], timeoutMs: number): Promise<string | undefined> =>
      new Promise((resolve) => {
        try {
          const child = spawn(UVX, args, { timeout: timeoutMs, windowsHide: true })
          let out = ""
          let errOut = ""
          child.stdout?.on("data", (d) => (out += d))
          child.stderr?.on("data", (d) => (errOut += d))
          const timer = setTimeout(() => {
            dlog(`${args[3]} timed out after ${timeoutMs}ms stderr=${errOut.slice(0, 200)}`)
            try { child.kill() } catch {}
            resolve(undefined)
          }, timeoutMs)
          child.on("close", (code) => {
            clearTimeout(timer)
            const text = !out || !out.trim() ? undefined : out.trim()
            dlog(`${args[3]} -> code=${code} len=${text?.length ?? 0} stderr=${errOut.slice(0, 200)}`)
            resolve(text)
          })
          child.on("error", (e) => {
            clearTimeout(timer)
            dlog(`${args[3]} spawn error ${String(e)}`)
            resolve(undefined)
          })
          try { child.stdin?.end() } catch {}
        } catch (e) {
          dlog(`${args[3]} threw ${String(e)}`)
          resolve(undefined)
        }
      })

    let cache: string | undefined
    let cacheAt = 0
    let pending: Promise<string | undefined> | undefined

    const readBrief = (): Promise<string | undefined> => {
      if (cache && Date.now() - cacheAt < TTL_MS) return Promise.resolve(cache)
      if (pending) return pending
      pending = runBM(
        ["--python", "3.12", "basic-memory", "hook", "session-start", "--project-dir", dir],
        15000,
      ).then((t) => {
        pending = undefined
        if (t) {
          cache = t
          cacheAt = Date.now()
        }
        return t
      })
      return pending
    }

    let okfCache: string | undefined
    let okfCacheAt = 0

    const readOkfCheck = (): Promise<string | undefined> => {
      if (okfCache && Date.now() - okfCacheAt < 60 * 60 * 1000) {
        return Promise.resolve(okfCache)
      }
      return runBM(["--python", "3.12", "basic-memory", "okf", "check", KB_DIR], 60000).then(
        (t) => {
          if (t) {
            okfCache = t
            okfCacheAt = Date.now()
          }
          return t
        },
      )
    }

    // Prime the brief during setup so the first model call resolves from cache
    // instead of racing a subprocess spawn.
    void readBrief()

    // `context` runs for every agent-loop model call (first prompt and every
    // tool-driven continuation), so the brief stays in context all session.
    await ctx.session.hook("context", async (event) => {
      dlog("context hook fired")
      const parts: string[] = []
      const brief = await readBrief()
      if (brief) parts.push(brief)
      const okf = await readOkfCheck()
      if (okf) parts.push(`KB conformance: ${okf}`)
      if (parts.length === 0) {
        dlog("nothing to inject yet")
        return
      }
      const text = [
        '<context key="basicmemory.kb-brief">',
        ...parts,
        "</context>",
        "This brief is generated by the basic-memory-brief plugin from the",
        "`tahirs-list-kb` knowledge base. Honor the Memory discipline rules in",
        "AGENTS.md: consult the `basic-memory` MCP for cross-cutting knowledge,",
        "and write reusable knowledge back to the KB in the same turn it is",
        "learned.",
      ].join("\n")
      try {
        ;(event as unknown as { system: { push(p: unknown): void } }).system.push({
          type: "text",
          text,
        })
        dlog(`pushed ${text.length} chars into system`)
      } catch (e) {
        dlog(`push failed: ${String(e)}`)
      }
    })
    dlog("context hook registered")
  },
})
